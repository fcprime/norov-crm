import assert from 'node:assert/strict';
import { DEFAULT_COLUMNS, validateTarget, dateInPeriod, planTemplate } from '../supabase/functions/client-reports/sheet-target.ts';
const t=validateTarget({sheet_id:0,since:'2026-09-24',until:'2026-10-23',first_row:2,last_row:31,columns:DEFAULT_COLUMNS})!;
const metric={day:'2026-10-08',campaigns:['Campaign'],leads:26,spend:67.55,impressions:7125,clicks:84,messages:1};
assert.equal(dateInPeriod('08.10',t),'2026-10-08');
assert.equal(dateInPeriod('07.10.2026',t),'2026-10-07');
assert.equal(dateInPeriod('Загалом:',t),null);
assert.equal(dateInPeriod((Date.parse('2026-10-08')-Date.UTC(1899,11,30))/86400000,t),'2026-10-08');
const dates=[['07.10'],['08.10'],['09.10'],['Загалом:']];
const data=[['07.10','manual',26],['08.10'],['09.10'],['Загалом:','=SUM(C2:C31)']];
const plan=planTemplate(t,[metric],dates,data,'2026-10-08');
assert.equal(plan.written,1);assert.equal(plan.writes[0].row,3);assert.equal(plan.writes[0].column,'B');assert.equal(plan.writes.find(w=>w.key==='ctr')!.value,84/7125);
assert.ok(plan.writes.every(w=>w.column!=='A'));assert.equal(data[0][1],'manual');
assert.equal(planTemplate(t,[{...metric,day:'2026-10-07'}],dates,data,'2026-10-08').writes.length,0);
assert.equal(planTemplate(t,[metric],dates,[[],['08.10','=IF(TRUE,"",0)']], '2026-10-08').skipped,1);
assert.equal(planTemplate(t,[metric],dates,[[],['08.10','',0]], '2026-10-08').skipped,1);
assert.throws(()=>planTemplate(t,[metric],[['08.10'],['08.10']],[], '2026-10-08'),/Дубль/);
assert.throws(()=>planTemplate(t,[metric],[['09.10']],[], '2026-10-08'),/немає рядка/);
assert.throws(()=>planTemplate(t,[{...metric,day:'2026-10-24'}],dates,data, '2026-10-08'),/поза періодом/);
assert.throws(()=>validateTarget({...t,columns:{...DEFAULT_COLUMNS,spend:'A'}}),/Колонки/);
assert.throws(()=>validateTarget({...t,sheet_id:-1}));
const winter={...t,since:'2026-12-24',until:'2027-01-23'};
assert.equal(dateInPeriod('01.01',winter),'2027-01-01');
assert.equal(dateInPeriod('31.12',winter),'2026-12-31');
console.log('PASS: template dates, serials, year boundary, exact row, formulas/manual/zero preserved, duplicates/missing/outside rejected');
